float B2[8]    = { 0.000000,0.241898,0.210201,-0.174508,-0.133965,0.217212,-0.220094,0.271101 };

float W3[2][8] = { { 0.395289, 0.400523, 0.621361, -0.275782, -0.649938, 0.627573, 1.385915, 0.718889 },
  { 0.193408, 0.866843, 0.715027, -0.266146, -0.698388, 0.502692, 1.655647, 0.507712 }
};
float B3[2]    = { 0.230758,0.189398 };

/* ==== SCALER ==== */
float X_SCALE[2] = { 0.05597627949180255, 0.0036144277401256816 };
float X_MIN[2]   = { 0.50503590598448, 0.45783583898114777 };
float Y_SCALE[2] = { 0.040027218508585836, 0.5885815185403178 };
float Y_MIN[2]   = { -0.4009526478005043, -0.0005885815185403178 };

void nn_pid(float e, float de, float* Kp, float* Kd)
{
    /* normalize input */
    float x[2];
    x[0] = (e  - X_MIN[0]) * X_SCALE[0];
    x[1] = (de - X_MIN[1]) * X_SCALE[1];

    float h1[8], h2[8];

    /* layer 1 */
    for(int i=0;i<8;i++){
        h1[i] = relu(W1[i][0]*x[0] + W1[i][1]*x[1] + B1[i]);
    }

    /* layer 2 */
    for(int i=0;i<8;i++){
        h2[i] = B2[i];
        for(int j=0;j<8;j++)
            h2[i] += W2[i][j] * h1[j];
        h2[i] = relu(h2[i]);
    }

    /* output */
    float y[2] = {B3[0], B3[1]};
    for(int i=0;i<8;i++){
        y[0] += W3[0][i] * h2[i];
        y[1] += W3[1][i] * h2[i];
    }

    /* denormalize */
    *Kp = y[0] / Y_SCALE[0] + Y_MIN[0];
    *Kd = y[1] / Y_SCALE[1] + Y_MIN[1];
//     printf("e=%f de=%f | en=%f den=%f\n",
//        e, de,
//        (e  - X_MIN[0]) * X_SCALE[0],
//        (de - X_MIN[1]) * X_SCALE[1]);
}
